// A working ratchet retains its source revision even if repository evidence is reloaded.
const mlsClientRevisions = new WeakMap<MlsGroupClient, string | null>();
function cloneCheckpointClient(client: MlsGroupClient, validator: Parameters<typeof MlsGroupClient.cloneWithValidator>[1]): MlsGroupClient {
  const working = MlsGroupClient.cloneWithValidator(client, validator);
  const revision = mlsClientRevisions.get(client);
  if (revision === undefined) throw new Error('MLS client has no source checkpoint revision');
  mlsClientRevisions.set(working, revision);
  return working;
}
