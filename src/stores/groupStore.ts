type GroupWirePayload =
  | {
      v: 1;
      type: 'message';
      id: string;
      text: string;
      replyTo?: GroupReplyReference;
      /** Encrypted-blob attachment metadata (Suite file/image sharing). */
      attachment?: BlobAttachment;
    }
  | { v: 1; type: 'reaction'; targetId: string; emoji: string; remove: boolean }
  | { v: 1; type: 'delete'; targetId: string };

function parseGroupWirePayload(raw: string, fallbackId: string): GroupWirePayload {
  try {
    const parsed = JSON.parse(raw) as Partial<GroupWirePayload>;
    if (parsed.v === 1 && parsed.type === 'message' && typeof parsed.text === 'string') {
      // Attachments arrive as structured data and are re-validated here, so a
      // malformed payload is dropped rather than rendered.
      const attachment = normalizeBlobAttachment((parsed as { attachment?: unknown }).attachment);
      return {
        v: 1,
        type: 'message',
        id: typeof parsed.id === 'string' && parsed.id ? parsed.id : fallbackId,
        text: parsed.text,
        ...(parsed.replyTo ? { replyTo: parsed.replyTo as GroupReplyReference } : {}),
        ...(attachment ? { attachment } : {}),
      };
    }
    if (
      parsed.v === 1 &&
      parsed.type === 'reaction' &&
      typeof parsed.targetId === 'string' &&
      typeof parsed.emoji === 'string'
    ) {
      return {
        v: 1,
        type: 'reaction',
        targetId: parsed.targetId,
        emoji: parsed.emoji.slice(0, 16),
        remove: parsed.remove === true,
      };
    }
    if (parsed.v === 1 && parsed.type === 'delete' && typeof parsed.targetId === 'string') {
      return { v: 1, type: 'delete', targetId: parsed.targetId };
    }
  } catch {
    // Legacy Suite messages were raw plaintext rather than a JSON envelope.
  }
  return { v: 1, type: 'message', id: fallbackId, text: raw };
}

