// Group mutations need a CSRF token. The raw `api` client has no global
// CSRF interceptor, so we attach the token to every state-changing call.
// POSTs reuse the auth store's postWithFreshCsrf (fetches a fresh token,
// attaches X-CSRF-Token, retries once on CSRF failure). PATCH/DELETE use the
// real HTTP methods with the token read from the auth store.
async function authed<T = unknown>(
  method: 'post' | 'patch' | 'delete',
  url: string,
  payload: unknown,
  operation: GroupOperation,
): Promise<T> {
  operation.assertCurrent();
  const authStore = useAuthStore();

  async function attempt(): Promise<T> {
    await operation.wait(() => authStore.fetchCsrfToken());
    const token = authStore.csrfToken || '';
    const headers = token ? { 'X-CSRF-Token': token } : {};
    if (method === 'post') {
      const { data } = await operation.wait(() => api.post<T>(url, payload, { headers }));
      return data;
    }
    if (method === 'patch') {
      const { data } = await operation.wait(() => api.patch<T>(url, payload, { headers }));
      return data;
    }
    const { data } = await operation.wait(() => api.delete<T>(url, { headers }));
    return data;
  }

  try {
    return await attempt();
  } catch (err) {
    // Retry once on CSRF failure with a freshly fetched token.
    if (
      err instanceof Error &&
      (err.message.includes('csrf') ||
        (err as { response?: { status?: number } })?.response?.status === 403)
    ) {
      return attempt();
    }
    throw err;
  }
}



/**
 * Load the current device's long-term Ed25519 identity key (the same key used
 * by the 1:1 Vault). Used to bind MLS leaves to a verifiable identity — the
 * "mourn layer" parity with 1:1 messaging.
 */
async function getMyIdentityKeyPair(operation: GroupOperation): Promise<MlsIdentityKeyPair | null> {
  operation.assertCurrent();
  const vaultStore = useVaultStore();
  const uid = operation.uid;
  if (!uid || uid === 'unknown') return null;
  const signKey = await vaultStore.keyManager.getStoredKey(`vault_identity_priv_${uid}`);
  const publicKey = await vaultStore.keyManager.getStoredKey(`vault_identity_pub_${uid}`);
  operation.assertCurrent();
  if (!signKey || !publicKey) return null;
  return { signKey, publicKey };
}

/** IndexedDB key for a group's local decrypted message history (mirrors 1:1). */
function groupMessagesKey(groupId: string, uid: string): string {
  return `group_messages_${groupId}_uid_${uid}`;
}

function groupHiddenMessagesKey(groupId: string, uid: string): string {
  return `group_hidden_messages_${groupId}_uid_${uid}`;
}

function groupSyncKey(groupId: string, uid: string): string {
  return `group_sync_${groupId}_uid_${uid}`;
}

async function loadHiddenGroupMessageIds(groupId: string, operation: GroupOperation): Promise<Set<string>> {
  const uid = operation.uid;
  if (!uid) return new Set();
  const stored = await get<string[] | undefined>(groupHiddenMessagesKey(groupId, uid));
  return new Set(Array.isArray(stored) ? stored : []);
}



/** Load a group's local decrypted message history from IndexedDB (plaintext, like 1:1). */
async function loadGroupMessages(groupId: string, operation: GroupOperation): Promise<GroupMessage[]> {
  const uid = operation.uid;
  if (!uid) return [];
  const stored = await get<GroupMessage[] | undefined>(groupMessagesKey(groupId, uid));
  return Array.isArray(stored) ? stored : [];
}

